fn sof_dims(stream: &[u8]) -> (u32, u32) {
    let sof = stream
        .windows(2)
        .position(|w| w == [0xFF, 0xF7])
        .expect("SOF55");
    let h = u16::from_be_bytes([stream[sof + 5], stream[sof + 6]]);
    let w = u16::from_be_bytes([stream[sof + 7], stream[sof + 8]]);
    (u32::from(w), u32::from(h))
}

fn assert_errval_rejected(name: &str, stream: &[u8]) {
    // Repair only the selector so these minimized malformed headers still
    // reach the corrupt entropy codes after selector validation was added.
    let mut repaired = stream.to_vec();
    let sos = repaired.windows(2).position(|b| b == [0xff, 0xda]).unwrap();
    repaired[sos + 5] = 1;
    let stream = repaired.as_slice();
    match jpegls::decode_image(stream) {
        Err(CodecError::Truncated { .. }) => {}
        other => panic!("{name}: decode_image -> {other:?}"),
    }
    let (w, h) = sof_dims(stream);
    match jpegls::decode(stream, w, h) {
        Err(CodecError::Truncated { .. }) => {}
        other => panic!("{name}: decode -> {:?}", other.map(|_| ())),
    }
}

